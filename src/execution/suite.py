from __future__ import annotations

"""Build the complete test suite: crawled tests + the LLM assertions that hold.

DANTE turns the crawl paths into a JUnit suite without assertions; the
pipeline asks the LLM for each test's assertions. This module puts the two
together:

1. every assertion statement of a test's answer is executed on its own, in
   isolation on the state saved just before the test (one wrong line must
   not discard the others);
2. the statements that hold are written into the test's method, in a copy of
   the DANTE project (``EnrichedTestSuite``, methods in crawl order);
3. the whole enriched suite runs once, in order, on a freshly installed app,
   and must pass — a suite that fails on the app it was built from is not
   delivered.

An answer that declares helper variables is kept or dropped as a whole,
since its statements cannot run apart.
"""

import json
import re
import shutil
import subprocess
import time
from pathlib import Path
from typing import Callable

from ..config import Config
from ..data.store import ResultStore
from ..ingest.dante import _TEST_METHOD_RE, crawled_variant_source, ingest_dante_suite, to_test_records
from ..llm.prompt_builder import CRAWLED_TREATMENT
from ..llm.response_parser import has_extra_statements, validate_assertion
from .java_injector import ensure_assert_imports, fill_placeholders
from .reference import (
    classpath_of,
    mvn,
    ReferenceRunError,
    _install_with_dante,
    load_reference,
    run_isolated,
    run_junit,
)

Log = Callable[[str], None]

SUITE_CLASS = "EnrichedTestSuite"


def suite_dir(config: Config, app: str) -> Path:
    return config.output_dir / "generated-suite" / app


def split_statements(code: str) -> list[str]:
    """Top-level Java statements of an answer (`;` outside strings, chars and
    parentheses), comment lines dropped, whitespace normalized."""
    lines = [l for l in code.split("\n") if not l.strip().startswith("//")]
    text = "\n".join(lines)
    statements, current, depth, quote, escaped = [], [], 0, None, False
    for ch in text:
        current.append(ch)
        if quote:
            if escaped:
                escaped = False
            elif ch == "\\":
                escaped = True
            elif ch == quote:
                quote = None
        elif ch in "\"'":
            quote = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        elif ch == ";" and depth == 0:
            statements.append(" ".join("".join(current).split()))
            current = []
    rest = " ".join("".join(current).split())
    if rest:
        statements.append(rest)
    return statements


def _units(answer: str) -> list[str]:
    """The pieces of an answer that are kept or dropped: each assertion
    statement, or the whole answer when it declares helper statements."""
    if not validate_assertion(answer):
        return []
    if has_extra_statements(answer):
        return [answer.strip()]
    return split_statements(answer)


def _enriched_source(suite_source: str, kept: dict[str, list[str]]) -> str:
    """DANTE's suite class renamed, run in crawl order (test00, test01, ...),
    with each method's kept assertions appended to its body."""
    source = suite_source
    for match in reversed(list(_TEST_METHOD_RE.finditer(suite_source))):
        assertions = kept.get(match.group(1), [])
        if not assertions:
            continue
        block = "\n\t\t// assertions generated by the LLM, each verified on the app\n" + "\n".join(
            "\t\t" + line for a in assertions for line in a.split("\n")
        )
        end = match.end(2)
        source = source[:end] + block + source[end:]
    source = re.sub(r"public class \w+", f"@FixMethodOrder(MethodSorters.NAME_ASCENDING)\npublic class {SUITE_CLASS}",
                    source, count=1)
    source = source.replace("import org.junit.Test;",
                            "import org.junit.Test;\nimport org.junit.FixMethodOrder;\n"
                            "import org.junit.runners.MethodSorters;", 1)
    return ensure_assert_imports(source)


def generate_suite(config: Config, app: str, model: str, run: int = 1, log: Log = print) -> dict:
    from .dante_runner import _toolchain_env

    load_reference(config, app, "crawled")
    root = suite_dir(config, app)
    if root.exists():
        shutil.rmtree(root)
    root.mkdir(parents=True)

    crawled = {t.class_name: t for t in ingest_dante_suite(
        app, config.get_dante_suite_path(app), config.output_dir / "crawled" / app)}
    store = ResultStore(config.output_dir / "results.db")
    rows = {r["class_name"]: r for r in store.get_all_results()
            if r["app"] == app and r["source"] == "crawled" and r["model"] == model
            and r["treatment"] == CRAWLED_TREATMENT and r["run"] == run}
    store.close()
    missing = sorted(set(crawled) - set(rows))
    if missing:
        raise ReferenceRunError(
            f"No {model} answer (run {run}) for: {', '.join(missing)}. "
            f"Run 'bewt-pipeline run --app {app} --source crawled --execute' first.")

    # 1. each assertion statement alone, on the state saved before its test
    tests = []
    order = sorted(crawled, key=lambda c: int(re.sub(r"\D", "", crawled[c].method_name)))
    for class_name in order:
        test = crawled[class_name]
        source = crawled_variant_source(to_test_records([test], "")[0], test.trace_comment)
        checks = []
        for i, unit in enumerate(_units(rows[class_name]["generated_assertion"] or "")):
            filled, _ = fill_placeholders(source, unit)
            compiled, result = run_isolated(
                config, app, class_name, filled, root / "checks" / class_name / str(i), source="crawled")
            holds = bool(compiled.success and result and result.passed)
            reason = "" if holds else (
                (result.error_message if result else "; ".join(compiled.errors)) or "")[:300]
            checks.append({"assertion": unit, "holds": holds, "reason": reason})
        kept = [c["assertion"] for c in checks if c["holds"]]
        tests.append({"class": class_name, "method": test.method_name,
                      "answer_holds": bool(rows[class_name]["passes"]),
                      "assertions": checks, "kept": len(kept)})
        log(f"  {class_name}: {len(kept)}/{len(checks)} assertions hold")

    # 2. write the enriched suite into a copy of the DANTE project
    project = root / "project"
    shutil.copytree(config.get_dante_testsuite_project_path(app), project,
                    ignore=shutil.ignore_patterns("target", "coverage-reports", "all-coverage-reports"))
    suite_source = config.get_dante_suite_path(app).read_text()
    kept_by_method = {t["method"]: [c["assertion"] for c in t["assertions"] if c["holds"]] for t in tests}
    suite_file = project / "src" / "main" / "java" / "tests" / f"{SUITE_CLASS}.java"
    suite_file.write_text(_enriched_source(suite_source, kept_by_method))

    # 3. the whole suite, in crawl order, on a freshly installed app
    env = _toolchain_env()
    for cmd in ([mvn(), "-q", "compile"],
                [mvn(), "-q", "dependency:build-classpath", "-Dmdep.outputFile=classpath.txt"]):
        result = subprocess.run(cmd, cwd=str(project), capture_output=True, text=True, timeout=900, env=env)
        if result.returncode != 0:
            raise ReferenceRunError(f"{' '.join(cmd)} failed:\n{(result.stdout + result.stderr)[-2000:]}")
    classpath = classpath_of(project / "target" / "classes", (project / "classpath.txt").read_text().strip())
    log("  Installing a fresh app container and running the enriched suite...")
    _install_with_dante(config, app)
    suite_run = run_junit(classpath, f"tests.{SUITE_CLASS}", timeout=3600, env=env, cwd=project)

    checked = sum(len(t["assertions"]) for t in tests)
    kept_total = sum(t["kept"] for t in tests)
    manifest = {
        "app": app, "model": model, "run": run,
        "suite": str(suite_file),
        "tests": len(tests),
        "tests_with_assertions": sum(1 for t in tests if t["kept"]),
        "assertions_generated": checked,
        "assertions_kept": kept_total,
        "answers_holding_whole": sum(1 for t in tests if t["answer_holds"]),
        "suite_run": {"passed": suite_run.passed, "seconds": suite_run.time_seconds,
                      "message": suite_run.error_message[:1000]},
        "created_at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "per_test": tests,
    }
    (root / "manifest.json").write_text(json.dumps(manifest, indent=2))
    return manifest

