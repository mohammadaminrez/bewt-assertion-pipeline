from __future__ import annotations

"""Build prompts for each treatment variant.

Context is added step by step, so each treatment contains everything the
previous one had plus one more source: A=code, B=+comments, C=+HTML,
D=+project code (D is the full condition).
"""

from dataclasses import dataclass

from ..models import TestRecord
from ..parsing.java_parser import PLACEHOLDER


@dataclass(frozen=True)
class Ingredients:
    """Which context sources a treatment's prompt includes."""
    comments: bool   # Gherkin "Then" clauses rendered as // Assert that ... comments
    html: bool       # captured HTML page source at the assertion point
    project: bool    # project code: Page Objects + Strings.java constants


_INGREDIENTS = {
    "A": Ingredients(comments=False, html=False, project=False),
    "B": Ingredients(comments=True, html=False, project=False),
    "C": Ingredients(comments=True, html=True, project=False),
    "D": Ingredients(comments=True, html=True, project=True),
}

TREATMENTS = tuple(_INGREDIENTS.keys())


def treatment_ingredients(treatment: str) -> Ingredients:
    """Return the context sources a treatment includes."""
    treatment = treatment.upper()
    if treatment not in _INGREDIENTS:
        raise ValueError(
            f"Treatment {treatment} is not valid (valid: {', '.join(TREATMENTS)})"
        )
    return _INGREDIENTS[treatment]


# Crawled (DANTE/Crawljax) tests reuse the same ingredient booleans, but the
# `project` source does not exist for them: A=code, B=+action-trace comment,
# C=+state DOM. D is meaningless and therefore not offered.
_CRAWLED_INGREDIENTS = {
    "A": Ingredients(comments=False, html=False, project=False),
    "B": Ingredients(comments=True, html=False, project=False),
    "C": Ingredients(comments=True, html=True, project=False),
}

CRAWLED_TREATMENTS = tuple(_CRAWLED_INGREDIENTS.keys())


def crawled_treatment_ingredients(treatment: str) -> Ingredients:
    """Context sources a treatment includes for crawler-generated tests."""
    treatment = treatment.upper()
    if treatment not in _CRAWLED_INGREDIENTS:
        raise ValueError(
            f"Treatment {treatment} is not valid for crawled tests "
            f"(valid: {', '.join(CRAWLED_TREATMENTS)})"
        )
    return _CRAWLED_INGREDIENTS[treatment]


SYSTEM_PROMPT = """You are an expert Java/Selenium test engineer. You are given a JUnit/Selenium test method where the assertion(s) have been removed and replaced with a TODO placeholder.

Your task: Generate ONLY the missing Java assertion statement(s) that should replace the placeholder.

Rules:
- Output ONLY the Java assertion code (e.g., assertEquals, assertTrue, assertFalse)
- Do NOT include imports, class declarations, or method signatures
- Do NOT include explanations or markdown formatting
- Use JUnit 4 assertions (org.junit.Assert)
- The assertion should verify the expected behavior of the test
- If multiple assertions are needed, output each on its own line"""


CRAWLED_SYSTEM_PROMPT = """You are an expert Java/Selenium test engineer. You are given a JUnit/Selenium test method that was automatically generated by a web crawler: it replays a sequence of user actions on a web application, but it has NO assertion — a TODO placeholder marks where the assertion(s) belong.

Your task: Generate the Java assertion statement(s) that should replace the placeholder, verifying the application state the test reaches at that point.

Rules:
- Output ONLY the Java assertion code (e.g., assertEquals, assertTrue, assertFalse)
- Assert a meaningful, user-visible outcome of the actions performed (page content, element text, element presence) — not incidental markup details
- Use only the `driver` WebDriver variable already in scope (e.g. driver.findElement(...), driver.getTitle(), driver.getCurrentUrl())
- Do NOT include imports, class declarations, or method signatures
- Do NOT include explanations or markdown formatting
- Use JUnit 4 assertions (org.junit.Assert)
- If multiple assertions are needed, output each on its own line"""


def build_crawled_assertion_prompt(
    record: TestRecord,
    *,
    variant_source: str,
    include_comments: bool,
    html_content: str | None = None,
) -> tuple[str, str]:
    """Assemble the prompt for a crawler-generated (assertion-less) test.

    Mirrors ``build_assertion_prompt`` but with the crawled-test system prompt
    and wording: comments here are an auto-generated action trace, and the HTML
    is the page source captured at the assertion point by the reference run.
    """
    intro = [
        "Write the missing assertion(s) for the following crawler-generated "
        "Selenium test where the TODO comment is."
    ]
    if include_comments:
        intro.append(
            "A comment above the placeholder describes the actions the test "
            "performs and the state it reaches."
        )

    user = "\n".join(intro) + f"\n\nTest code:\n```java\n{variant_source}\n```"

    if html_content:
        user += (
            "\n\nHTML page content at the assertion point:\n"
            f"```html\n{html_content}\n```"
        )

    return CRAWLED_SYSTEM_PROMPT, user


def build_assertion_prompt(
    record: TestRecord,
    *,
    variant_source: str,
    include_comments: bool,
    html_content: str | None = None,
    strings_source: str | None = None,
    page_object_sources: dict[str, str] | None = None,
) -> tuple[str, str]:
    """Assemble a prompt from whichever context sources are provided.

    The caller decides which pieces to pass based on the treatment's
    ingredients (see ``treatment_ingredients``). The descriptive text only
    mentions a source when it is actually included.
    """
    intro = [
        "Complete the following Selenium test by writing the missing "
        "assertion(s) where the TODO comment is."
    ]
    if include_comments:
        intro.append(
            "Descriptive comments have been added to explain what the "
            "assertion should check."
        )
    placeholders = variant_source.count(PLACEHOLDER)
    if placeholders > 1:
        intro.append(
            f"The test has {placeholders} placeholders, numbered (1) to ({placeholders}). "
            "Write the assertion(s) for each placeholder, and start each group with a "
            "line containing only its marker, e.g. `// (1)`."
        )

    user = "\n".join(intro) + f"\n\nTest code:\n```java\n{variant_source}\n```"

    if html_content:
        # The whole page source as the browser returned it at the assertion
        # point — never cut or cleaned, so nothing on the page (hidden
        # elements, the title) is lost.
        user += (
            "\n\nHTML page content at the assertion point:\n"
            f"```html\n{html_content}\n```"
        )

    if strings_source:
        user += f"\n\nProject constants (Strings.java):\n```java\n{strings_source}\n```"

    if page_object_sources:
        user += "\n\nRelevant Page Object classes:\n"
        for class_name, source in page_object_sources.items():
            user += f"\n--- {class_name}.java ---\n```java\n{source}\n```\n"

    return SYSTEM_PROMPT, user
