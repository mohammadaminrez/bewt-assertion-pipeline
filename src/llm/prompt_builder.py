from __future__ import annotations

"""Build prompts for each treatment variant.

Context is added step by step, so each treatment contains everything the
previous one had plus one more source: A=code, B=+specification (the Gherkin
scenario as a comment), C=+HTML, D=+project code (D is the full condition).
"""

from dataclasses import dataclass

from ..models import TestRecord
from ..parsing.java_parser import PLACEHOLDER


@dataclass(frozen=True)
class Ingredients:
    """Which context sources a treatment's prompt includes."""
    comments: bool   # the test's whole Gherkin feature file, as a comment above @Test
    html: bool       # captured HTML page source at the assertion point
    project: bool    # project code: Page Objects + Strings.java constants


_INGREDIENTS = {
    "A": Ingredients(comments=False, html=False, project=False),
    "B": Ingredients(comments=True, html=False, project=False),
    "C": Ingredients(comments=True, html=True, project=False),
    "D": Ingredients(comments=True, html=True, project=True),
}

TREATMENTS = tuple(_INGREDIENTS.keys())


def treatment_ingredients(treatment: str) -> Ingredients:
    """Return the context sources a treatment includes."""
    treatment = treatment.upper()
    if treatment not in _INGREDIENTS:
        raise ValueError(
            f"Treatment {treatment} is not valid (valid: {', '.join(TREATMENTS)})"
        )
    return _INGREDIENTS[treatment]


# Crawled (DANTE/Crawljax) tests have no treatments: the prompt always holds
# the test code, its action-trace comment and the page at the assertion
# point. Answers are stored under this label, which that context had when
# the crawled tests were also run without the page (A/B), so the results
# collected then keep their keys.
CRAWLED_TREATMENT = "C"


# Deliberately minimal: it states the task and the output format the harness
# needs (the answer is pasted in place of the placeholder, then compiled and
# run), and nothing about what to check or which API to use.
SYSTEM_PROMPT = """You are given a Selenium test in which the assertion(s) have been replaced by a TODO placeholder. Write the Java assertion statement(s) that replace it.

Your answer is inserted into the test as-is, then compiled and run, so output only Java statements: no explanations, no markdown, no imports or method declarations."""


# Minimal, like SYSTEM_PROMPT: the task and the output format the harness
# needs, nothing about what to check or which API to use.
CRAWLED_SYSTEM_PROMPT = """You are given a Selenium test generated by a web crawler. It has no assertion: a TODO placeholder marks where the assertion(s) belong. Write the Java assertion statement(s) for that placeholder.

Your answer is inserted into the test as-is, then compiled and run, so output only Java statements: no explanations, no markdown, no imports or method declarations."""


def build_crawled_assertion_prompt(
    record: TestRecord,
    *,
    variant_source: str,
    html_content: str,
) -> tuple[str, str]:
    """Assemble the prompt for a crawler-generated (assertion-less) test.

    Mirrors ``build_assertion_prompt`` but with the crawled-test system prompt
    and wording: the comment is the auto-generated action trace, and the HTML
    is the page source captured at the assertion point by the reference run.
    """
    user = (
        "Write the missing assertion(s) for the following crawler-generated "
        "Selenium test where the TODO comment is.\n"
        "A comment above the placeholder describes the actions the test "
        "performs."
        f"\n\nTest code:\n```java\n{variant_source}\n```"
        "\n\nHTML page content at the assertion point:\n"
        f"```html\n{html_content}\n```"
    )
    return CRAWLED_SYSTEM_PROMPT, user


def build_assertion_prompt(
    record: TestRecord,
    *,
    variant_source: str,
    include_comments: bool,
    html_content: str | None = None,
    strings_source: str | None = None,
    page_object_sources: dict[str, str] | None = None,
) -> tuple[str, str]:
    """Assemble a prompt from whichever context sources are provided.

    The caller decides which pieces to pass based on the treatment's
    ingredients (see ``treatment_ingredients``). The descriptive text only
    mentions a source when it is actually included.
    """
    intro = [
        "Complete the following Selenium test by writing the missing "
        "assertion(s) where the TODO comment is."
    ]
    if include_comments:
        intro.append(
            "The test's specification (its Gherkin scenario) is included as a "
            "comment above the test method."
        )
    placeholders = variant_source.count(PLACEHOLDER)
    if placeholders > 1:
        intro.append(
            f"The test has {placeholders} placeholders, numbered (1) to ({placeholders}). "
            "Write the assertion(s) for each placeholder, and start each group with a "
            "line containing only its marker, e.g. `// (1)`."
        )

    user = "\n".join(intro) + f"\n\nTest code:\n```java\n{variant_source}\n```"

    if html_content:
        # The whole page source as the browser returned it at the assertion
        # point — never cut or cleaned, so nothing on the page (hidden
        # elements, the title) is lost.
        user += (
            "\n\nHTML page content at the assertion point:\n"
            f"```html\n{html_content}\n```"
        )

    if strings_source:
        user += f"\n\nProject constants (Strings.java):\n```java\n{strings_source}\n```"

    if page_object_sources:
        user += "\n\nRelevant Page Object classes:\n"
        for class_name, source in page_object_sources.items():
            user += f"\n--- {class_name}.java ---\n```java\n{source}\n```\n"

    return SYSTEM_PROMPT, user
